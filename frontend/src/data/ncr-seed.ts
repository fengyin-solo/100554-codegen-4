// 不合格品台账示例：三条处置车道、冲突评审、复检合格/不合格都铺一条，打开即可演示。
function event(
  at: string,
  action: string,
  actor: string,
  department: string,
  fromStatus: NcrStatus | '',
  toStatus: NcrStatus,
  note: string,
): TimelineEvent {
  return { at, action, actor, department, fromStatus, toStatus, note }
}

function proposal(
  disposition: Disposition,
  source: DispositionProposal['source'],
  actor: string,
  department: string,
  at: string,
  opinion: string,
): DispositionProposal {
  return { disposition, source, actor, department, at, opinion }
}

type SeedPatch = Partial<NcrOrder> & Pick<NcrOrder, 'code' | 'status' | 'batchNo' | 'productName' | 'heldSince'>

function order(patch: SeedPatch, index: number): NcrOrder {
  return {
    abnormal: false,
    sourceType: '成品检验',
    sourceNo: '',
    quantity: '',
    nonConformity: '',
    foundBy: '王检验',
    foundAt: patch.heldSince,
    disposition: '',
    proposals: [],
    reviewOpinion: '',
    reviewer: '',
    reviewedAt: '',
    executor: '',
    executionRequirement: '',
    reworkBatchNo: '',
    executedAt: '',
    concessionNote: '',
    concessionApprover: '',
    concessionAt: '',
    recheckResult: '',
    recheckInspector: '',
    recheckNote: '',
    recheckedAt: '',
    finalConclusion: '',
    deviationCode: '',
    timeline: [],
    ...patch,
    id: index,
  }
}

